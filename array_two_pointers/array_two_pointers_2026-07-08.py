# Three Sum
# Difficulty: Medium
# Topic: Array, Two Pointers
# Time: O(n^2) | Space: O(1)
#
# Approach:
# Sort the array and use a two-pointer technique to find pairs that sum to the negative of the current element. Avoid duplicates by skipping repeated values during iteration.
#
# Solution:

def three_sum(nums):
    nums.sort()
    result = []
    for i in range(len(nums) - 2):
        if i > 0 and nums[i] == nums[i - 1]:
            continue
        left, right = i + 1, len(nums) - 1
        while left < right:
            total = nums[i] + nums[left] + nums[right]
            if total < 0:
                left += 1
            elif total > 0:
                right -= 1
            else:
                result.append([nums[i], nums[left], nums[right]])
                while left < right and nums[left] == nums[left + 1]:
                    left += 1
                while left < right and nums[right] == nums[right - 1]:
                    right -= 1
                left += 1
                right -= 1
    return result
